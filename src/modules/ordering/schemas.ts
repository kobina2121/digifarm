import { z } from "zod";

const id = z.uuid("Something went wrong. Please reload and try again.");

/** Up to three decimals, e.g. "2.5" tonnes. */
const quantity = z
  .string()
  .trim()
  .regex(/^\d{1,11}(\.\d{1,3})?$/, "Enter a number, e.g. 10 or 2.5")
  .refine((v) => Number(v) > 0, "Enter more than zero");

export const cartItemSchema = z.object({
  listingId: id,
  quantity,
  /** "add" from a listing page; "set" when editing the cart. */
  mode: z.enum(["add", "set"]).default("set"),
});
export type CartItemInput = z.input<typeof cartItemSchema>;

export const checkoutSchema = z.object({
  addressId: z.uuid("Choose where to deliver"),
  /** Generated by the checkout page, so a double tap never places two orders. */
  idempotencyKey: z.uuid(),
  notes: z
    .string()
    .trim()
    .max(500, "Keep notes under 500 characters")
    .transform((v) => (v === "" ? undefined : v))
    .optional(),
});
export type CheckoutInput = z.input<typeof checkoutSchema>;

export const cancelOrderSchema = z.object({
  reason: z
    .string()
    .trim()
    .max(300, "Keep it under 300 characters")
    .transform((v) => (v === "" ? undefined : v))
    .optional(),
});
export type CancelOrderInput = z.input<typeof cancelOrderSchema>;
